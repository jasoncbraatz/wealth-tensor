"""Where else the manuscript restates a registered figure -- the surface §5.4's and §7's
guards each leave open, measured rather than assumed.

WHY THIS EXISTS
---------------
Two guards now watch registered figures in paper III, and between them they cover two
sections and one token class:

  * `test_cell_provenance` watches §5.4, and only its `\\d+\\.\\d+×` multipliers.
  * `test_ledger_provenance` watches §7's falsifier ledger, all figure kinds.

That looked like coverage until the second file's mutation drill measured it. The drill
mutated `**0.103 against 0.030**` expecting to break §7's row; `str.replace(..., 1)` took
the FIRST match, at line 1432 -- inside §5.4, ~150 lines above §7 -- and the suite stayed
green because §5.4's guard reads multipliers and 0.103 is not one. A false miss, and the
false miss was the finding:

    THE SAME REGISTERED FIGURE IS PRINTED IN UP TO FIVE PLACES IN THIS MANUSCRIPT.
    REG-003's α̂ appears eleven times across §4.4, §4.10, §5.4, §7 and §9. Two guards
    watched two of those. A re-run moves the result doc; whichever copies nobody
    updated stay behind, and every one of them is a well-formed sentence.

This file closes that by counting. For each figure §7's ledger declares, it pins HOW MANY
TIMES each section of the manuscript prints it. A restatement that appears, vanishes, or
drifts to a neighbouring value changes a count, and the suite says which section.

WHY COUNTS AND NOT A SET OF SECTIONS
------------------------------------
A section set would have been cheaper and is nearly useless: §4.10 prints α̂ = 0.408 five
times, so changing one of them to 0.409 leaves the set `{4.10, ...}` intact and the guard
green -- while 0.409, being declared nowhere, is watched by nothing at all. The count is
what makes a single drifted copy visible.

The cost is honest and worth naming: an edit that legitimately adds or removes a mention
turns this suite red and the author must update a number here. That is the same bargain
`CELLS` struck in `test_cell_provenance`, and the same one the phrase set and the
hand-audit ceilings struck elsewhere in this repo. The failure message names the section
and both counts so the update is mechanical.

WHAT IS DELIBERATELY NOT COUNTED
--------------------------------
Three of the ledger's figures are tokens the manuscript also uses for unrelated
quantities, where a count would pin the wrong thing and churn on edits that have nothing
to do with any registered run. They are named in `NOT_COUNTED` with the collision, and
`test_every_ledger_figure_is_either_counted_or_excused` makes the exclusion list a
declaration rather than an omission -- add a figure to §7's ledger and this file goes red
until someone puts it in one list or the other.

Offline, like every test here. It reads the manuscript only.
"""

