def test_every_ledger_figure_is_either_counted_or_excused():
    """§7's ledger and this file cannot drift apart silently.

    Add a figure to the ledger and it must be counted here or named in NOT_COUNTED with
    the collision that excuses it.
    """
    unaccounted = LEDGER_FIGURES - set(REACH) - set(NOT_COUNTED)
    assert not unaccounted, (
        f"§7's ledger declares figures this file neither counts nor excuses: "
        f"{sorted(unaccounted)}. Add each to REACH (with its measured per-section counts) "
        f"or to NOT_COUNTED (with the quantity whose token it collides with)."
    )
    stray = (set(REACH) | set(NOT_COUNTED)) - LEDGER_FIGURES
    assert not stray, (
        f"this file counts figures §7's ledger no longer declares: {sorted(stray)}. "
        f"If the ledger dropped them, drop them here too."
    )
    assert not (set(REACH) & set(NOT_COUNTED)), "a figure is both counted and excused"


@pytest.mark.parametrize("figure", sorted(REACH))
def test_the_manuscript_restates_the_figure_exactly_where_declared(figure, measured):
    """THE LOAD-BEARING CHECK.

    A copy that drifts, appears or vanishes changes a count. Section sets would not catch
    a single drifted copy among five; counts do.
    """
    declared, actual = REACH[figure], measured[figure]
    assert actual == declared, (
        f"{figure} is printed in a pattern the repository has not declared.\n"
        f"  declared: {dict(sorted(declared.items()))}\n"
        f"  measured: {dict(sorted(actual.items()))}\n"
        f"Sections whose count moved: "
        f"{sorted(set(declared) ^ set(actual) | {k for k in set(declared) & set(actual) if declared[k] != actual[k]})}. "
        f"Either a restatement drifted from the run that owns it -- the defect this file "
        f"exists for -- or the manuscript legitimately gained or lost a mention and the "
        f"count needs updating."
    )


