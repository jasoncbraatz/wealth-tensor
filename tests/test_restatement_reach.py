def _section_labels(lines: list[str]) -> list[str]:
    """The section each line belongs to: the most recent heading, most specific wins.

    Numbered headings reduce to their number (`### 4.10 · The shape…` → `4.10`) so a
    retitled section does not churn every count; unnumbered ones keep their title
    (`Abstract`, `References`).
    """
    labels, current = [], "title"
    for line in lines:
        head = re.match(r"^#{1,4}\s+(.*)$", line)
        if head:
            title = head.group(1)
            numbered = re.match(r"^((?:Appendix )?[A-Z0-9]+(?:\.[0-9]+)*)\s*·", title)
            current = numbered.group(1) if numbered else title.split("·")[0].strip()
        labels.append(current)
    return labels


def _mentions(text: str, value: str) -> bool:
    """As in `test_ledger_provenance`: a number in its own right, not a fragment."""
    return re.search(rf"(?<![\d.]){re.escape(value)}(?![\d])", text) is not None


@pytest.fixture(scope="module")
def measured() -> dict[str, dict[str, int]]:
    lines = PAPER.read_text(encoding="utf-8").split("\n")
    labels = _section_labels(lines)
    out: dict[str, dict[str, int]] = {}
    for figure in list(REACH) + list(RESULT_REACH) + list(RESULT_NOT_COUNTED):
        counts: dict[str, int] = {}
        for label, line in zip(labels, lines):
            if _mentions(line, figure):
                counts[label] = counts.get(label, 0) + 1
        out[figure] = counts
    return out


